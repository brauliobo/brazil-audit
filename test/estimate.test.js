import test from 'node:test'
import assert from 'node:assert/strict'
import { estimate, simplex } from '../src/estimate.js'

// Places drawn from a known transfer matrix: three first-round groups (a, b, others) and abstention, four outcomes (a, b, blank and null, abstention).
const TRUE = [[0.9, 0.02, 0.02, 0.06], [0.02, 0.9, 0.02, 0.06], [0.3, 0.5, 0.05, 0.15], [0.05, 0.05, 0.05, 0.85]]
const places = (n) => Array.from({ length: n }, (_, k) => {
  const size = 500 + ((k * 7919) % 5000)
  const mix = [0.2 + ((k * 31) % 40) / 100, 0.1 + ((k * 17) % 50) / 100, 0.05 + ((k * 13) % 15) / 100].map((s) => s * size / 1.2)
  const x = [...mix, size - mix.reduce((a, b) => a + b, 0)]
  return { x, y: TRUE[0].map((_, j) => x.reduce((s, xi, i) => s + xi * TRUE[i][j], 0)) }
})

test('the projection onto the simplex is a distribution', () => {
  const p = simplex([0.8, 0.8, -0.3])
  assert.ok(Math.abs(p.reduce((a, b) => a + b, 0) - 1) < 1e-12)
  assert.ok(p.every((v) => v >= 0))
})

test('the transfer matrix is recovered from places that were generated by it', () => {
  const { T, low, high, fit } = estimate(places(300), { boot: 8 })
  T.forEach((row, i) => row.forEach((v, j) => assert.ok(Math.abs(v - TRUE[i][j]) < 0.03, `T[${i}][${j}] = ${v}`)))
  assert.ok(T.every((row) => Math.abs(row.reduce((a, b) => a + b, 0) - 1) < 1e-9))
  assert.ok(fit > 0.95)
})

test('without variation between the places every group votes like the whole', () => {
  const same = Array.from({ length: 40 }, () => ({ x: [100, 100, 50, 50], y: [150, 100, 20, 30] }))
  const { T } = estimate(same, { boot: 2 })
  T.forEach((row) => [0.5, 1 / 3, 0.0667, 0.1].forEach((v, j) => assert.ok(Math.abs(row[j] - v) < 0.01)))
})
